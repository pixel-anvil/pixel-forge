// Generator for packages/raster/src/trig-table.ts: the Q16 quarter-wave sine table used by trig.ts.
//
// Usage (from the repo root):
//   node packages/raster/scripts/gen-trig-table.mjs           write src/trig-table.ts
//   node packages/raster/scripts/gen-trig-table.mjs --check   exit 1 if the committed file is stale
//
// Maths: exact integer arithmetic only. Values are BigInt fixed point with FRAC_BITS fractional bits;
// pi comes from Machin's formula (pi = 16 atan(1/5) - 4 atan(1/239)) and sin from its Taylor series.
// Each truncating step loses < 1 ulp (2^-256), so the computed sin(x) * 65536 is within ~2^-240 of the
// true value. Entries are rounded half away from zero; the generator refuses to emit a value whose
// fractional part is within 2^-200 of .5 (none is: by Niven's theorem sin of a rational number of
// degrees is rational only for 0, +-1/2, +-1, all of which are integers once multiplied by 65536).
//
// The runtime never evaluates this: trig.ts imports the committed literals and expands the quarter wave
// to the full 1440-entry table with exact symmetries (sin(180-x) = sin(x), sin(-x) = -sin(x)).
// The raster tests import `exactSinQ16` from here and check every one of the 1440 runtime entries
// against a direct evaluation (no symmetry used), plus a float64 cross-check.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

/** Fixed-point resolution of the generator's arithmetic. */
export const FRAC_BITS = 256n;
const ONE = 1n << FRAC_BITS;
/** Table scale: sin values are stored times 65536 (Q16). */
export const Q16 = 65536n;
/** Table steps per degree (0.25 degree resolution). */
export const STEPS_PER_DEGREE = 4;
/** Steps in a full turn. */
export const STEPS = 360 * STEPS_PER_DEGREE;
/** Entries 0..QUARTER inclusive cover 0..90 degrees. */
export const QUARTER = 90 * STEPS_PER_DEGREE;

/** atan(1/x) in fixed point, x a positive integer > 1 (alternating series, truncating division). */
function atanInv(x) {
  const bx = BigInt(x);
  const x2 = bx * bx;
  let power = ONE / bx; // 1 / x^(2k+1)
  let sum = power;
  for (let k = 1n; power !== 0n; k++) {
    power /= x2;
    const term = power / (2n * k + 1n);
    sum += k % 2n === 1n ? -term : term;
  }
  return sum;
}

/** pi in fixed point (Machin's formula). */
export const PI = 16n * atanInv(5) - 4n * atanInv(239);

/** sin(x) for fixed-point x (any sign, |x| <= 2 pi is plenty), by the Taylor series. */
function sinFixed(x) {
  const x2 = (x * x) / ONE;
  let term = x;
  let sum = x;
  for (let n = 1n; term !== 0n; n++) {
    term = (-term * x2) / ONE / (2n * n * (2n * n + 1n));
    sum += term;
  }
  return sum;
}

const TIE_GUARD = ONE >> 200n; // refuse to round values this close to .5

/**
 * round_half_away_from_zero(sin(k * 0.25 deg) * 65536) for any integer k, evaluated directly at
 * x = (k mod 1440) * pi / 720 (exact integer reduction; no trigonometric symmetry is used).
 * Returns `{ value, tieDistance }`: the rounded integer and |frac - 1/2| as a JS number.
 */
export function exactSinQ16(k) {
  const m = ((k % STEPS) + STEPS) % STEPS;
  const x = (PI * BigInt(m)) / BigInt(STEPS / 2); // m * pi / 720
  const v = sinFixed(x) * Q16; // fixed point, value * 65536
  const neg = v < 0n;
  const a = neg ? -v : v;
  const whole = a / ONE;
  const frac = a % ONE;
  const half = ONE / 2n;
  const dist = frac > half ? frac - half : half - frac;
  if (dist < TIE_GUARD) throw new Error(`ambiguous rounding at step ${String(k)}`);
  const rounded = frac >= half ? whole + 1n : whole; // half away from zero (on |v|)
  const value = Number(neg ? -rounded : rounded);
  // Number() of the scaled distance: only for reporting, never for a decision.
  const tieDistance = Number((dist * 1_000_000_000_000n) / ONE) / 1e12;
  return { value: value === 0 ? 0 : value, tieDistance };
}

/** The quarter-wave table: entries for 0, 0.25, ..., 90 degrees (QUARTER + 1 values). */
export function quarterSinQ16() {
  const values = [];
  let minTieDistance = 1;
  for (let k = 0; k <= QUARTER; k++) {
    const { value, tieDistance } = exactSinQ16(k);
    values.push(value);
    minTieDistance = Math.min(minTieDistance, tieDistance);
  }
  return { values, minTieDistance };
}

function render(values, minTieDistance) {
  return `// GENERATED by packages/raster/scripts/gen-trig-table.mjs. Do not edit by hand.
// Regenerate: node packages/raster/scripts/gen-trig-table.mjs (check: --check).

/**
 * Quarter-wave sine table in Q16: entry \`i\` is \`sin(i * 0.25°) * 65536\` for \`i = 0..${String(QUARTER)}\`
 * (0° to 90° inclusive), rounded half away from zero. Computed with exact BigInt arithmetic
 * (256 fractional bits, Machin's pi, Taylor series). No entry is a rounding tie: the fractional part
 * closest to .5 is ${minTieDistance.toFixed(6)} away from it.
 * \`trig.ts\` expands it to the full 1440-entry table with exact symmetries.
 */
export const QUARTER_SIN_Q16: readonly number[] = [${values.join(', ')}];
`;
}

async function format(source, file) {
  const prettier = await import('prettier');
  const options = (await prettier.resolveConfig(file)) ?? {};
  return prettier.format(source, { ...options, filepath: file });
}

async function main() {
  const here = dirname(fileURLToPath(import.meta.url));
  const file = join(here, '..', 'src', 'trig-table.ts');
  const { values, minTieDistance } = quarterSinQ16();
  const out = await format(render(values, minTieDistance), file);
  if (process.argv.includes('--check')) {
    let current;
    try {
      current = readFileSync(file, 'utf8');
    } catch {
      current = '';
    }
    if (current !== out) {
      console.error(`${file} is stale; run node packages/raster/scripts/gen-trig-table.mjs`);
      process.exit(1);
    }
    console.log(`${file} is up to date`);
    return;
  }
  writeFileSync(file, out);
  console.log(
    `wrote ${file}: ${String(values.length)} entries, min distance to a .5 tie ${String(minTieDistance)}`,
  );
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
